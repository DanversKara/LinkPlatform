#!/usr/bin/env python3
"""Build the single-file LinkPlatform v12 installer.

Embeds the whole project tree (app/, Dockerfile, docker-compose.yml,
Caddyfile, .env.example, scripts/, requirements.txt) as base64 blobs inside
a generated bash installer, then writes it to
~/workspace/your_files/linkplatform-v12-install.sh.

Re-run any time the tree changes (e.g. after other agents finish app/).
The installer itself is upgrade-safe: it never regenerates secrets on
re-install and merges new .env keys without touching existing values.
"""
import base64
import hashlib
import stat
from pathlib import Path

VERSION = "12.0.0"
PROJECT = Path(__file__).resolve().parent
OUT = Path.home() / "workspace" / "your_files" / "linkplatform-v12-install.sh"

# Fixed files, in a stable order. app/ is walked recursively below.
FIXED_FILES = [
    "requirements.txt",
    "Dockerfile",
    "docker-compose.yml",
    "Caddyfile",
    ".env.example",
    "setup.sh",
    "scripts/linkplatform",
    "scripts/backup.sh",
    "scripts/update.sh",
]

SKIP_DIRS = {".venv", "__pycache__", ".git", ".hg", "node_modules", ".pytest_cache"}
SKIP_SUFFIXES = {".pyc", ".pyo"}


def collect_files():
    rels = []
    for rel in FIXED_FILES:
        p = PROJECT / rel
        if p.is_file():
            rels.append(rel)
        else:
            print(f"  note: {rel} not found, skipping")
    appdir = PROJECT / "app"
    if appdir.is_dir():
        for p in sorted(appdir.rglob("*")):
            if not p.is_file():
                continue
            if p.suffix in SKIP_SUFFIXES:
                continue
            if any(part in SKIP_DIRS for part in p.parts):
                continue
            rels.append(str(p.relative_to(PROJECT)))
    return rels


def file_block(i, rel):
    """One self-delimiting heredoc block that decodes a file into $LP_DIR."""
    data = (PROJECT / rel).read_bytes()
    b64 = base64.encodebytes(data).decode("ascii")
    tag = hashlib.sha256(data).hexdigest()[:8]
    marker = f"LPEOF_{i:04d}_{tag}"
    return f'lp_write "{rel}" <<\'{marker}\'\n{b64}{marker}\n'


BODY = r'''#!/usr/bin/env bash
# =====================================================================
# LinkPlatform v12 — single-file installer (generated by pack.py)
# Installs the app container (+ optional Caddy HTTPS edge when a domain
# is configured). Safe to re-run: upgrades keep your existing .env and data.
# =====================================================================
set -euo pipefail
LP_VERSION="@@VERSION@@"
LP_DIR="${LP_DIR:-$HOME/linkplatform}"
SUDO=""
FRESH=0
EDGE=()
ADMIN_PASSWORD=""

step() { echo; echo "==> $*"; }
warn() { echo "WARNING: $*" >&2; }
die()  { echo "ERROR: $*" >&2; exit 1; }

lp_write() { # $1 = path relative to LP_DIR; base64 payload on stdin
    local rel="$1"
    local dest="$LP_DIR/$rel"
    mkdir -p "$(dirname "$dest")"
    base64 -d > "$dest"
}

dcrun() { ( cd "$LP_DIR" && $COMPOSE "$@" ); }

# --- privilege helper ----------------------------------------------------
if [ "$(id -u)" -eq 0 ]; then
    SUDO=""
elif command -v sudo >/dev/null 2>&1; then
    SUDO="sudo"
else
    warn "not running as root and 'sudo' not found — OS package installs will be skipped"
fi

apt_install() { # $* = packages
    if [ -z "$SUDO" ] && [ "$(id -u)" -ne 0 ]; then
        die "need root or sudo to install packages: $* (install them manually and re-run)"
    fi
    $SUDO apt-get update
    $SUDO apt-get install -y "$@"
}

# --- 0. prerequisites ------------------------------------------------------
step "Checking prerequisites (LinkPlatform v${LP_VERSION})"
command -v base64 >/dev/null 2>&1  || { echo "installing coreutils (base64)..."; apt_install coreutils; }
command -v curl >/dev/null 2>&1    || { echo "installing curl..."; apt_install curl; }
command -v openssl >/dev/null 2>&1 || { echo "installing openssl..."; apt_install openssl; }

if ! command -v docker >/dev/null 2>&1; then
    step "Installing Docker (docker.io)"
    apt_install docker.io
    $SUDO systemctl enable --now docker 2>/dev/null || $SUDO service docker start 2>/dev/null || true
    command -v docker >/dev/null 2>&1 || die "docker is still missing after install"
else
    echo "Docker OK: $(docker --version)"
fi

# Resolve the compose command: prefer the v2 plugin, fall back to the
# standalone v1 binary (Ubuntu's repos don't carry docker-compose-plugin).
if docker compose version >/dev/null 2>&1; then
    COMPOSE="docker compose"
elif command -v docker-compose >/dev/null 2>&1; then
    COMPOSE="docker-compose"
else
    step "Installing docker compose"
    apt_install docker-compose-plugin 2>/dev/null || apt_install docker-compose || true
    if docker compose version >/dev/null 2>&1; then
        COMPOSE="docker compose"
    elif command -v docker-compose >/dev/null 2>&1; then
        COMPOSE="docker-compose"
    else
        die "docker compose is still missing. If you use Docker Desktop, enable WSL integration (Settings > Resources > WSL Integration); otherwise install the compose plugin from https://docs.docker.com/compose/install/"
    fi
fi
echo "Compose OK: $($COMPOSE version | head -1)"

# The CLI existing is not enough — the daemon must answer.
if ! docker info >/dev/null 2>&1; then
    die "docker is installed but its daemon is not reachable. If you use Docker Desktop: make sure it is running and enable WSL integration (Settings > Resources > WSL Integration > your distro), then re-run. Otherwise start the daemon with: sudo systemctl start docker"
fi

# --- 1. install dir: fresh vs upgrade -----------------------------------------
step "Preparing install directory: $LP_DIR"
mkdir -p "$LP_DIR"
if [ -f "$LP_DIR/.env" ]; then
    TS="$(date +%Y%m%d-%H%M%S)"
    cp "$LP_DIR/.env" "$LP_DIR/.env.bak.$TS"
    chmod 600 "$LP_DIR/.env.bak.$TS"
    echo "Existing install detected — .env backed up to .env.bak.$TS and will be REUSED (secrets preserved)."
else
    FRESH=1
    echo "Fresh install."
fi

# --- 2. write embedded files ---------------------------------------------------
step "Writing application files to $LP_DIR"
@@FILES@@
chmod +x "$LP_DIR/scripts/linkplatform" "$LP_DIR/scripts/backup.sh" "$LP_DIR/scripts/update.sh"
echo "  application files written."

# --- 3. configuration ------------------------------------------------------------
if [ "$FRESH" -eq 1 ]; then
    step "First-time configuration"
    DOMAIN=""; ADMIN_EMAIL="admin@example.com"; APP_PORT="8000"
    if [ -t 0 ]; then
        read -rp "Public domain for auto-HTTPS (blank = local/LAN only): " DOMAIN || true
        read -rp "Admin email [admin@example.com]: " _e || true
        [ -n "${_e:-}" ] && ADMIN_EMAIL="$_e"
        read -rp "Host port for the app [8000]: " _p || true
        [ -n "${_p:-}" ] && APP_PORT="$_p"
    else
        echo "  (non-interactive shell — using defaults; edit $LP_DIR/.env afterwards)"
    fi
    DOMAIN="$(printf '%s' "$DOMAIN" | tr '[:upper:]' '[:lower:]' | tr -d '[:space:]')"
    case "$ADMIN_EMAIL" in
        *@*.*) ;;
        *) warn "admin email '$ADMIN_EMAIL' looks invalid — fix it in $LP_DIR/.env" ;;
    esac

    if command -v openssl >/dev/null 2>&1; then
        SECRET_KEY="$(openssl rand -hex 32)"
        ADMIN_PASSWORD="$(openssl rand -base64 15 | tr -d '\n')"
    else
        SECRET_KEY="$(python3 -c 'import secrets; print(secrets.token_hex(32))')"
        ADMIN_PASSWORD="$(python3 -c 'import secrets; print(secrets.token_urlsafe(15))')"
    fi

    LAN_IPS="$(hostname -I 2>/dev/null | tr ' ' '\n' | grep -E '^[0-9a-fA-F.:]+$' | paste -sd, - || true)"
    ALLOWED_HOSTS="localhost,127.0.0.1"
    [ -n "$LAN_IPS" ] && ALLOWED_HOSTS="$ALLOWED_HOSTS,$LAN_IPS"
    if [ -n "$DOMAIN" ]; then
        ALLOWED_HOSTS="$ALLOWED_HOSTS,$DOMAIN"
        TRUST_PROXY="true"; BASE_URL="https://$DOMAIN"; APP_BIND="127.0.0.1"
    else
        TRUST_PROXY="false"; BASE_URL=""; APP_BIND="0.0.0.0"
    fi

    sed -e "s|^APP_PORT=.*|APP_PORT=$APP_PORT|" \
        -e "s|^APP_BIND=.*|APP_BIND=$APP_BIND|" \
        -e "s|^DOMAIN=.*|DOMAIN=$DOMAIN|" \
        -e "s|^BASE_URL=.*|BASE_URL=$BASE_URL|" \
        -e "s|^SECRET_KEY=.*|SECRET_KEY=$SECRET_KEY|" \
        -e "s|^ALLOWED_HOSTS=.*|ALLOWED_HOSTS=$ALLOWED_HOSTS|" \
        -e "s|^TRUST_PROXY=.*|TRUST_PROXY=$TRUST_PROXY|" \
        -e "s|^ADMIN_EMAIL=.*|ADMIN_EMAIL=$ADMIN_EMAIL|" \
        -e "s|^ADMIN_PASSWORD=.*|ADMIN_PASSWORD=$ADMIN_PASSWORD|" \
        "$LP_DIR/.env.example" > "$LP_DIR/.env"
    chmod 600 "$LP_DIR/.env"
    echo "  .env written (mode 600)."
else
    step "Merging new settings into existing .env (your values are kept)"
    while IFS= read -r line || [ -n "$line" ]; do
        case "$line" in ''|\#*) continue ;; esac
        key="${line%%=*}"
        case "$key" in *[!A-Z0-9_]* ) continue ;; esac
        if ! grep -Eq "^${key}=" "$LP_DIR/.env"; then
            printf '%s\n' "$line" >> "$LP_DIR/.env"
            echo "  added new key with default: $key"
        fi
    done < "$LP_DIR/.env.example"
fi

# --- 4. reverse proxy --------------------------------------------------------------
step "Configuring reverse proxy"
DOMAIN_NOW="$(grep -E '^DOMAIN=' "$LP_DIR/.env" | cut -d= -f2- || true)"
if [ -n "$DOMAIN_NOW" ]; then
    sed "s|{\$DOMAIN}|$DOMAIN_NOW|g" "$LP_DIR/Caddyfile" > "$LP_DIR/Caddyfile.new"
    mv "$LP_DIR/Caddyfile.new" "$LP_DIR/Caddyfile"
    echo "  Caddy will serve https://$DOMAIN_NOW with automatic TLS."
    EDGE=(--profile edge)
else
    echo "  No domain configured — serving plain HTTP on the app port (no Caddy)."
    EDGE=()
fi

# --- 5. build + start -----------------------------------------------------------------
step "Building the app image (a few minutes on first run)"
dcrun build app

step "Starting services"
dcrun "${EDGE[@]}" up -d
dcrun ps

# --- 6. wait for health ------------------------------------------------------------------
PORT="$(grep -E '^APP_PORT=' "$LP_DIR/.env" | cut -d= -f2- || true)"
PORT="${PORT:-8000}"
step "Waiting for the app to become healthy (up to 120s)"
ok=0
for i in $(seq 1 120); do
    if curl -fsS -o /dev/null "http://127.0.0.1:${PORT}/api/health" 2>/dev/null; then
        ok=1; break
    fi
    sleep 1
done
if [ "$ok" -ne 1 ]; then
    echo "ERROR: app did not become healthy within 120s. Last 50 log lines:" >&2
    dcrun logs --tail=50 app >&2
    exit 1
fi
echo "  app is healthy."

# --- 7. smoke tests ------------------------------------------------------------------------
step "Running smoke tests"
HEALTH_JSON="$(curl -fsS "http://127.0.0.1:${PORT}/api/health")"
echo "  GET /api/health -> 200  ($HEALTH_JSON)"
LOGIN_OK=0
for p in /login /admin/login; do
    code="$(curl -sS -o /dev/null -w '%{http_code}' "http://127.0.0.1:${PORT}${p}" 2>/dev/null || echo 000)"
    echo "  GET ${p} -> ${code}"
    [ "$code" = "200" ] && LOGIN_OK=1
done
[ "$LOGIN_OK" -eq 1 ] || warn "no login page returned 200 on /login or /admin/login — verify the app routes"

# --- 8. install CLI -----------------------------------------------------------------------------
step "Installing the 'linkplatform' CLI"
BIN_SRC="$LP_DIR/scripts/linkplatform"
if [ -w /usr/local/bin ]; then
    cp "$BIN_SRC" /usr/local/bin/linkplatform
    echo "  installed to /usr/local/bin/linkplatform"
elif [ -n "$SUDO" ]; then
    $SUDO cp "$BIN_SRC" /usr/local/bin/linkplatform \
        && echo "  installed to /usr/local/bin/linkplatform (via sudo)"
else
    mkdir -p "$HOME/.local/bin"
    cp "$BIN_SRC" "$HOME/.local/bin/linkplatform"
    echo "  installed to $HOME/.local/bin/linkplatform"
    case ":$PATH:" in
        *":$HOME/.local/bin:"*) ;;
        *) warn "add \$HOME/.local/bin to your PATH to use the 'linkplatform' command" ;;
    esac
fi

# --- 9. summary ------------------------------------------------------------------------------------
LAN_IP="$(hostname -I 2>/dev/null | awk '{print $1}')"
LAN_IP="${LAN_IP:-<server-ip>}"
ADMIN_EMAIL_NOW="$(grep -E '^ADMIN_EMAIL=' "$LP_DIR/.env" | cut -d= -f2- || true)"
echo
echo "======================================================================"
echo " LinkPlatform v${LP_VERSION} installed successfully!"
echo "======================================================================"
echo "  Local URL : http://${LAN_IP}:${PORT}   (also http://localhost:${PORT})"
[ -n "$DOMAIN_NOW" ] && echo "  Public URL: https://${DOMAIN_NOW}   (DNS must point at this server)"
if [ "$FRESH" -eq 1 ]; then
    echo
    echo "  +----------------------------------------------------------------+"
    echo "  |  FIRST-INSTALL ADMIN CREDENTIALS — SAVE THESE SOMEWHERE SAFE   |"
    echo "  +----------------------------------------------------------------+"
    echo "      Email   : ${ADMIN_EMAIL_NOW}"
    echo "      Password: ${ADMIN_PASSWORD}"
    echo "  Log in and change the password immediately (Admin / Settings)."
fi
echo
echo "  CLI commands : linkplatform {start|stop|restart|logs [service]|status|backup|update|shell|health|version}"
echo "  Backups      : linkplatform backup   (to ${LP_DIR}/backups, newest 10 kept)"
echo "  Restore one  : cd ${LP_DIR} && $COMPOSE stop app && \\"
echo "                 docker run --rm -v linkplatform_data:/data -v ${LP_DIR}/backups:/backup alpine \\"
echo "                   sh -c 'rm -rf /data/* && tar xzf /backup/<file>.tar.gz -C /data' && \\"
echo "                 $COMPOSE start app"
echo "  Full reset   : (cd ${LP_DIR} && $COMPOSE down -v) && rm -rf ${LP_DIR}"
echo "  Config file  : ${LP_DIR}/.env  (mode 600 — keep it private)"
echo "======================================================================"
'''


def main():
    rels = collect_files()
    print(f"Embedding {len(rels)} files:")
    blocks = []
    for i, rel in enumerate(rels):
        size = (PROJECT / rel).stat().st_size
        print(f"  {rel} ({size} bytes)")
        blocks.append(file_block(i, rel))
    body = BODY.replace("@@VERSION@@", VERSION).replace("@@FILES@@", "".join(blocks))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(body, encoding="utf-8")
    OUT.chmod(OUT.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    print(f"\nWrote {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
